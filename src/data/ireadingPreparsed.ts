/**
 * Retrieve pre-parsed book info by title, bookNo, or ISBN
 */
export function getPreparsedIreadingBook(
  title?: string,
  bookNo?: string,
  isbn?: string
): ParsedIreadingBook | null {
  if (!title && !bookNo && !isbn) return null;

  // 1. Direct title exact match
  if (title && IREADING_PREPARSED_DATA[title]) {
    return IREADING_PREPARSED_DATA[title];
  }

  // 2. Cleaned title match
  const clean = (s: string) => s.replace(/[:：!！?？\s\(\)\（\）\[\]\【\】]/g, '').trim();
  const targetClean = title ? clean(title) : '';

  for (const key of Object.keys(IREADING_PREPARSED_DATA)) {
    const item = IREADING_PREPARSED_DATA[key];
    
    // Check ISBN
    if (isbn && item.isbn && item.isbn.replace(/[^0-9X]/gi, '') === isbn.replace(/[^0-9X]/gi, '')) {
      return item;
    }
    // Check BookNo
    if (bookNo && item.bookNo && item.bookNo === bookNo) {
      return item;
    }
    // Check clean title
    if (targetClean && clean(item.title).includes(targetClean)) {
      return item;
    }
    if (targetClean && targetClean.includes(clean(item.title))) {
      return item;
    }
  }

  return null;
}
