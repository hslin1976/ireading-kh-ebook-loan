export const ZHUYIN_DICT: Record<string, string> = {};
RAW_ZHUYIN_PAIRS.forEach(([k, v]) => {
  ZHUYIN_DICT[k] = v;
});

// Function to decompose Zhuyin string (e.g. "ㄏㄨㄟˋ" or "˙ㄉㄜ" or "ㄕ") into parts
export function decomposeZhuyin(zhuyinStr: string): {
  zhuyin: string;
  initial?: string;
  medial?: string;
  final?: string;
  tone?: string;
} {
  if (!zhuyinStr) return { zhuyin: '' };

  let tone = '';
  let cleanZhuyin = zhuyinStr;

  if (zhuyinStr.startsWith('˙') || zhuyinStr.endsWith('˙')) {
    tone = '˙';
    cleanZhuyin = zhuyinStr.replace(/˙/g, '');
  } else if (zhuyinStr.includes('ˊ')) {
    tone = 'ˊ';
    cleanZhuyin = zhuyinStr.replace(/ˊ/g, '');
  } else if (zhuyinStr.includes('ˇ')) {
    tone = 'ˇ';
    cleanZhuyin = zhuyinStr.replace(/ˇ/g, '');
  } else if (zhuyinStr.includes('ˋ')) {
    tone = 'ˋ';
    cleanZhuyin = zhuyinStr.replace(/ˋ/g, '');
  }

  // Initials (聲母)
  const initials = 'ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙ';
  // Medials (介母)
  const medials = 'ㄧㄨㄩ';
  // Finals (韻母)
  const finals = 'ㄚㄛㄜㄝㄞㄟㄠㄡㄢㄣㄤㄥㄦ';

  let initial = '';
  let medial = '';
  let final = '';

  for (let i = 0; i < cleanZhuyin.length; i++) {
    const char = cleanZhuyin[i];
    if (initials.includes(char) && !initial && !medial && !final) {
      initial = char;
    } else if (medials.includes(char) && !medial && !final) {
      medial = char;
    } else if (finals.includes(char) && !final) {
      final = char;
    }
  }

  return {
    zhuyin: zhuyinStr,
    initial: initial || undefined,
    medial: medial || undefined,
    final: final || undefined,
    tone: tone || undefined,
  };
}

// Convert a string to array of ZhuyinChar
export function stringToZhuyinChars(text: string): ZhuyinChar[] {
  const result: ZhuyinChar[] = [];

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const zhuyinStr = ZHUYIN_DICT[char];

    if (zhuyinStr && zhuyinStr !== char) {
      const parts = decomposeZhuyin(zhuyinStr);
      result.push({
        char,
        zhuyin: zhuyinStr,
        initial: parts.initial,
        medial: parts.medial,
        final: parts.final,
        tone: parts.tone,
      });
    } else {
      result.push({
        char,
      });
    }
  }

  return result;
}
